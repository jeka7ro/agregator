/**
 * Generate crisp SVG illustration data URI for Courier / Delivery items (Wolt, Glovo, Bolt, or Generic)
 */
function getCourierDeliverySvg(rawName = '') {
  const lower = String(rawName || '').toLowerCase()
  let bg = '#10b981' // Emerald default
  let badge = 'DELIVERY'
  if (lower.includes('wolt')) {
    bg = '#009de0'
    badge = 'WOLT'
  } else if (lower.includes('glovo')) {
    bg = '#ffc244'
    badge = 'GLOVO'
  } else if (lower.includes('bolt')) {
    bg = '#34d186'
    badge = 'BOLT'
  }
  const fg = lower.includes('glovo') ? '#1e293b' : '#ffffff'

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120" width="120" height="120">
    <rect width="120" height="120" rx="24" fill="${bg}"/>
    <rect x="18" y="14" width="84" height="22" rx="11" fill="rgba(0,0,0,0.18)"/>
    <text x="60" y="29" font-family="Arial, sans-serif" font-size="12" font-weight="900" fill="#ffffff" text-anchor="middle" letter-spacing="1">${badge}</text>
    <g transform="translate(18, 42)" fill="none" stroke="${fg}" stroke-width="5.5" stroke-linecap="round" stroke-linejoin="round">
      <circle cx="18" cy="50" r="11" fill="rgba(0,0,0,0.15)"/>
      <circle cx="68" cy="50" r="11" fill="rgba(0,0,0,0.15)"/>
      <path d="M8 36h22l10-18h18"/>
      <path d="M52 18l14 22H30"/>
      <rect x="4" y="14" width="22" height="18" rx="4" fill="${fg}" stroke="none"/>
      <path d="M58 12h10" stroke-width="6"/>
    </g>
  </svg>`
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`
}

/**
 * Get real product image URL from Syrve / iiko Cloud
 */
export function getProductImage(productName = '', brand = '', directUrl = null) {
  const rawLower = String(productName || '').toLowerCase()

  // 0. Dedicated Courier / Delivery illustration for delivery fee items (e.g. WOLT_BASE_DELIVERY, GLOVO_DELIVERY, Delivery, Livrare)
  if (
    rawLower.includes('delivery') ||
    rawLower.includes('livrare') ||
    rawLower.includes('curier') ||
    rawLower.includes('transport') ||
    rawLower.includes('taxa de drum')
  ) {
    return getCourierDeliverySvg(productName)
  }

  const clean = String(productName || '')
    .toLowerCase()
    .replace(/^(?:p_|pw_|rm_|sm_|ik_|ls_|[a-z0-9]{1,3}_)\s*/i, '')
    .replace(/[^a-z0-9\s♥]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

  // Sort keys longest-first so specific dish names (e.g. 'poke orez salmon classic', 'wok udon pui sos chinezesc')
  // always win over short generic tokens ('classic', 'shrimp', 'fusion', 'wok')
  const sortedEntries = Object.entries(SYRVE_DISH_IMAGES).sort((a, b) => b[0].length - a[0].length)

  // 1. Exact / Specific multi-word dish match (prioritized even over generic backend fallback URLs)
  for (const [key, url] of sortedEntries) {
    if (key.length >= 10 && clean.includes(key)) {
      return url
    }
  }

  const bLow = String(brand || '').toLowerCase()
  const isSushiBrandOrPrefix = bLow.includes('roll') || bLow.includes('sushi') || bLow.includes('love') || rawLower.startsWith('p_')

  // Use directUrl if valid and not the misassigned Teriyaki 25g sauce cup on non-sauce dishes
  // and not a Smash Me (/7601594/) burger photo on a Roll Master / Love Sushi / P_ item
  if (
    directUrl &&
    typeof directUrl === 'string' &&
    (directUrl.startsWith('http') || directUrl.startsWith('data:image')) &&
    !(directUrl.includes('e0d7070d-43d4-4195-bf79-a4488e2a9909') && !clean.includes('sos teriyaki 25')) &&
    !(isSushiBrandOrPrefix && directUrl.includes('/7601594/'))
  ) {
    return directUrl
  }

  // 1b. Shorter keyword match from SYRVE_DISH_IMAGES
  for (const [key, url] of sortedEntries) {
    if (clean.includes(key)) {
      if (isSushiBrandOrPrefix && url.includes('/7601594/')) continue
      return url
    }
  }

  // 2. Keyword fallback
  if (clean.includes('set') || clean.includes('roll') || clean.includes('sushi') || clean.includes('maki')) {
    return SYRVE_DISH_IMAGES['big party']
  }
  if (clean.includes('burger')) {
    if (bLow.includes('roll') || bLow.includes('sushi') || bLow.includes('love') || rawLower.startsWith('p_')) {
      return SYRVE_DISH_IMAGES['burger somon']
    }
    return SYRVE_DISH_IMAGES['cheesburger']
  }
  if (clean.includes('wok') || clean.includes('orez') || clean.includes('noodle')) {
    return SYRVE_DISH_IMAGES['wok']
  }
  if (clean.includes('poke')) {
    return SYRVE_DISH_IMAGES['poke']
  }

  // Brand default fallback
  if (bLow.includes('smash')) return SYRVE_DISH_IMAGES['cheesburger']
  if (bLow.includes('poki')) return SYRVE_DISH_IMAGES['poke']
  if (bLow.includes('crunch')) return SYRVE_DISH_IMAGES['crunch']

  return SYRVE_DISH_IMAGES['big party']
}
